// DECLARATION MERGING

export interface SVGAttributes extends AttributeProps<typeof SVGSymbols> {}


export class SVGAttributes extends Attributes {

	static override readonly Symbol: Record<string, symbol> = {
		...Attributes.Symbol,
		...SVGSymbols
	};


	static override readonly Names: Set<string> = new Set(
		Object.values(SVGAttributes.Symbol).map(s => s.description!)
	);


	static override readonly CamelCase: Set<string> = new Set(
		[...SVGAttributes.Names].filter(name => /[A-Z]/.test(name))
	);
}
